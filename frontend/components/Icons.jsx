// Maps a trait icon name (from backend persona.traits[i].icon) to its
// SVG component. Unknown names fall back to a message icon.
export function DynamicTraitIcon({ iconName, ...props }) {
  const map = {
    globe: GlobeIcon,
    message: MessageIcon,
    alert: AlertIcon,
    user: UserIcon,
    bar: BarIcon,
    shield: ShieldIcon
  };
  const Icon = map[iconName] || MessageIcon;
  return <Icon {...props} />;
}

// Maps an evidence type (backend evidence[i].type) to its SVG icon.
// Unknown types fall back to a link icon.
export function DynamicEvidenceIcon({ type, ...props }) {
  const map = {
    website: GlobeIcon,
    phone: PhoneIcon,
    email: MailIcon,
    upi: CardIcon,
    bank: BankIcon
  };
  const Icon = map[type] || LinkIcon;
  return <Icon {...props} />;
}
