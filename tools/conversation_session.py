"""
conversation_session.py
=======================
In-memory conversation state for ONE undercover investigation.

A session is the back-and-forth chat between the scammer (raw
messages pasted by the analyst) and the TraceAI decoy persona
(generated replies).

Message records are stored as dictionaries of the shape:

    {"role": "scammer" | "traceai", "message": "<text>"}

The formatted history string produced by ``get_history()`` is fed
into the ConversationAgent on every turn so the LLM never loses
track of what was already said.
"""


class ConversationSession:

    def __init__(self):
        """Start a fresh, empty conversation session."""

        self.history = []

    def add_scammer_message(self, message: str):
        """
        Record the latest raw scammer message.

        This is the analyst-pasted payload that arrives on /analyze.
        """

        self.history.append({
            "role": "scammer",
            "message": message
        })

    def add_traceai_reply(self, reply: str):
        """
        Record the persona reply generated by the ConversationAgent.
        """

        self.history.append({
            "role": "traceai",
            "message": reply
        })

    def get_history(self) -> str:
        """
        Serialise the whole dialogue into one readable transcript
        block, e.g.::

            SCAMMER: Dear SBI customer, your card is blocked...
            TRACEAI: Can you tell me how to verify this?

        The transcript is injected into the LLM prompt so the
        persona reply stays consistent with prior turns.
        """

        if not self.history:
            return "No previous conversation."

        history = ""

        for item in self.history:

            history += (
                f"{item['role'].upper()}: "
                f"{item['message']}\n"
            )

        return history

    def clear(self):
        """Reset the session (used on a new investigation)."""

        self.history.clear()
